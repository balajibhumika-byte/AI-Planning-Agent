from core.llm_client import get_ai_response


class Executor:
    """
    Executor Agent:
    Executes individual subtasks generated by the Planner.
    """

    def __init__(self):
        self.system_prompt = """
        You are an intelligent AI Task Executor.

        Your responsibility is to complete the given subtask.

        Follow these rules:

        1. Understand the subtask carefully.
        2. Provide a detailed and practical solution.
        3. Follow the expected output requirements.
        4. Use clear headings and organized information.
        5. Include examples, calculations or steps when useful.
        6. Avoid unnecessary information.
        7. Do not claim to have performed real-world actions.
           Provide plans and recommendations instead.
        """

    def execute_subtask(self, subtask, main_task):
        """
        Executes one subtask and returns its result.
        """

        if not isinstance(subtask, dict):
            raise ValueError("Invalid subtask provided.")

        title = subtask.get("title")
        description = subtask.get("description")
        expected_output = subtask.get("expected_output")

        if not all([
            isinstance(value, str) and value.strip()
            for value in [title, description, expected_output]
        ]):
            raise ValueError("Subtask information is incomplete.")

        messages = [
            {
                "role": "system",
                "content": self.system_prompt
            },
            {
                "role": "user",
                "content": f"""
                MAIN TASK:
                {main_task}

                SUBTASK:
                {title}

                DESCRIPTION:
                {description}

                EXPECTED OUTPUT:
                {expected_output}

                Complete this subtask and provide the result.
                """
            }
        ]

        try:
            result = get_ai_response(
                messages,
                temperature=0.4,
                max_tokens=1500
            )

            if not result or not result.strip():
                raise ValueError("AI returned an empty result.")

            return {
                "subtask_id": subtask.get("id"),
                "title": title,
                "status": "Completed",
                "result": result.strip()
            }

        except Exception as error:
            return {
                "subtask_id": subtask.get("id"),
                "title": title,
                "status": "Failed",
                "result": None,
                "error": str(error)
            }

    def execute_all(self, plan):
        """
        Executes all subtasks sequentially.
        """

        if not isinstance(plan, dict):
            raise ValueError("Invalid plan provided.")

        main_task = plan.get("task")
        subtasks = plan.get("subtasks")

        if not isinstance(main_task, str) or not main_task.strip():
            raise ValueError("Main task is missing.")

        if not isinstance(subtasks, list) or not subtasks:
            raise ValueError("No subtasks available for execution.")

        results = []

        for subtask in subtasks:
            result = self.execute_subtask(subtask, main_task)
            results.append(result)

            print(f"\nExecuting: {result['title']}")
            print(f"Status: {result['status']}")

        return results